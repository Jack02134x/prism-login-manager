#!/usr/bin/env python3
"""Regenerate common/Icons.qml.

Scans every .qml file in shell/ and themes/ for string literals that name a
Symbols Nerd Font glyph ("lock" -> md-lock, or a full name such as
"linux-hyprland") and writes a small lookup singleton with just those glyphs.
Needs fontTools (python-fonttools); only run by developers, never at login.
"""
import json
import re
import sys
from pathlib import Path

from fontTools.ttLib import TTFont

SHELL = Path(__file__).resolve().parent.parent
ROOT = SHELL.parent
FONT = "/usr/share/fonts/TTF/SymbolsNerdFont-Regular.ttf"

names = {n: cp for cp, n in TTFont(FONT).getBestCmap().items()}

found = {}
# names built at runtime (e.g. "battery_" + level) that never appear as literals
EXTRA = [f"battery_{n}" for n in range(10, 100, 10)] + [f"battery_charging_{n}" for n in range(10, 101, 10)]
for s in EXTRA:
    if "md-" + s in names:
        found[s] = names["md-" + s]

literal = re.compile(r'"([a-z0-9_\-]+)"')
sources = [p for p in list(SHELL.rglob("*.qml")) + list((ROOT / "themes").rglob("*.qml")) + list((ROOT / "themes").rglob("*.json")) if p.name != "Icons.qml"]
for src in sources:
    for s in literal.findall(src.read_text()):
        if "md-" + s in names:
            found[s] = names["md-" + s]
        elif s in names and "-" in s:
            found[s] = names[s]


def esc(cp):
    if cp <= 0xFFFF:
        return "\\u%04X" % cp
    v = cp - 0x10000
    return "\\u%04X\\u%04X" % (0xD800 + (v >> 10), 0xDC00 + (v & 0x3FF))


lines = [f'        "{k}": "{esc(found[k])}"' for k in sorted(found)]
out = """pragma Singleton

import QtQuick
import Quickshell

// Generated by scripts/gen-icons.py - Symbols Nerd Font glyphs used by PLM.
Singleton {
    readonly property var map: ({
%s
    })

    function get(name) {
        return map[name] ?? "";
    }
}
""" % ",\n".join(lines)
(SHELL / "common" / "Icons.qml").write_text(out)
print(f"{len(found)} icons", file=sys.stderr)
